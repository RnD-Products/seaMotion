// A sticky item pinned to the top or the bottom edge of the artboard: an uploaded picture or a line
// of text, aligned left, center or right and moved in from the edge by an offset in px.
function stickyControls(side: "bottom" | "top") {
  const target = (field: string): string => `sticky.${side}.${field}`;
  const typeIs = (type: "image" | "text") => ({ equals: type, target: target("type") }) as const;
  const active = { notEquals: "off", target: target("type") } as const;
  const base = { performanceReason: "Only changes what is drawn behind the design.", performanceRole: "responsiveness" } as const;
  return {
    [`${side}Type`]: {
      ...base,
      applicability: { all: [MODIFIER], mode: "conditional" },
      defaultValue: "off",
      label: side === "top" ? "Top item" : "Bottom item",
      options: [
        { label: "Off", value: "off" },
        { label: "Image", value: "image" },
        { label: "Text", value: "text" },
      ],
      target: target("type"),
      type: "segmented",
    },
    [`${side}Image`]: {
      ...base,
      applicability: { all: [MODIFIER, typeIs("image")], mode: "conditional" },
      defaultValue: EMPTY_IMAGE_SLOT,
      label: false,
      target: target("image"),
      type: imageSlotControl,
    },
    [`${side}ImageSize`]: {
      ...base,
      applicability: { all: [MODIFIER, typeIs("image")], mode: "conditional" },
      defaultValue: 100,
      description: "100% is a picture 80px tall; the width follows the picture's proportions.",
      label: "Scale",
      max: 500,
      min: 10,
      sliderValueKind: "continuous",
      step: 1,
      target: target("imageSize"),
      type: "slider",
      unit: "%",
    },
    [`${side}Text`]: {
      ...base,
      applicability: { all: [MODIFIER, typeIs("text")], mode: "conditional" },
      defaultValue: "",
      label: "Text",
      target: target("text"),
      textValueKind: "single-line",
      type: "text",
    },
    [`${side}TextSize`]: {
      ...base,
      applicability: { all: [MODIFIER, typeIs("text")], mode: "conditional" },
      defaultValue: 36,
      label: "Size",
      max: 200,
      min: 8,
      sliderValueKind: "continuous",
      step: 1,
      target: target("textSize"),
      type: "slider",
      unit: "px",
    },
    [`${side}TextColor`]: {
      ...base,
      applicability: { all: [MODIFIER, typeIs("text")], mode: "conditional" },
      defaultValue: "#111111",
      label: "Color",
      target: target("textColor"),
      type: "color",
    },
    [`${side}Align`]: {
      ...base,
      applicability: { all: [MODIFIER, active], mode: "conditional" },
      defaultValue: "left",
      label: "Align",
      options: [
        { label: "Left", value: "left" },
        { label: "Center", value: "center" },
        { label: "Right", value: "right" },
      ],
      target: target("align"),
      type: "segmented",
    },
    [`${side}Offset`]: {
      ...base,
      applicability: { all: [MODIFIER, active], mode: "conditional" },
      defaultValue: 24,
      description: side === "top" ? "Distance down from the top edge of the artboard." : "Distance up from the bottom edge of the artboard.",
      label: "Offset",
      max: 600,
      min: 0,
      sliderValueKind: "continuous",
      step: 1,
      target: target("offset"),
      type: "slider",
      unit: "px",
    },
  } as const;
}

